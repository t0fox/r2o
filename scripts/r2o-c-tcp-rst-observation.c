#include <stdint.h>
#include <stdio.h>
#include <string.h>

#include "d2k_journal.h"
#include "d2k_session.h"

static void записать_16(uint8_t *место, uint16_t число) {
    место[0] = (uint8_t)(число >> 8);
    место[1] = (uint8_t)число;
}

static void записать_32(uint8_t *место, uint32_t число) {
    место[0] = (uint8_t)(число >> 24);
    место[1] = (uint8_t)(число >> 16);
    место[2] = (uint8_t)(число >> 8);
    место[3] = (uint8_t)число;
}

static size_t собрать_приветствие(uint8_t *выход) {
    static const uint8_t имя[] = "example.test";
    uint8_t тело[128];
    size_t позиция = 0;
    тело[позиция++] = 0x03;
    тело[позиция++] = 0x03;
    memset(тело + позиция, 0, 32);
    позиция += 32;
    тело[позиция++] = 0;
    тело[позиция++] = 0;
    тело[позиция++] = 2;
    тело[позиция++] = 0x13;
    тело[позиция++] = 1;
    тело[позиция++] = 1;
    тело[позиция++] = 0;

    size_t длина_расширений = позиция;
    позиция += 2;
    size_t начало_расширений = позиция;
    тело[позиция++] = 0;
    тело[позиция++] = 0;
    size_t длина_sni = позиция;
    позиция += 2;
    size_t начало_sni = позиция;
    тело[позиция++] = 0;
    тело[позиция++] = 15;
    тело[позиция++] = 0;
    тело[позиция++] = 0;
    тело[позиция++] = 12;
    memcpy(тело + позиция, имя, sizeof имя - 1);
    позиция += sizeof имя - 1;
    записать_16(тело + длина_sni, (uint16_t)(позиция - начало_sni));
    записать_16(тело + длина_расширений,
                (uint16_t)(позиция - начало_расширений));

    выход[0] = 0x16;
    выход[1] = 0x03;
    выход[2] = 0x03;
    записать_16(выход + 3, (uint16_t)(позиция + 4));
    выход[5] = 1;
    выход[6] = (uint8_t)(позиция >> 16);
    выход[7] = (uint8_t)(позиция >> 8);
    выход[8] = (uint8_t)позиция;
    memcpy(выход + 9, тело, позиция);
    return позиция + 9;
}

static size_t собрать_tcp(uint8_t *пакет, const uint8_t *источник,
                          const uint8_t *назначение, uint16_t порт_источника,
                          uint16_t порт_назначения, uint8_t флаги, uint8_t ttl,
                          uint32_t номер, const uint8_t *данные, size_t длина) {
    size_t всего = 40 + длина;
    memset(пакет, 0, всего);
    пакет[0] = 0x45;
    записать_16(пакет + 2, (uint16_t)всего);
    пакет[8] = ttl;
    пакет[9] = 6;
    memcpy(пакет + 12, источник, 4);
    memcpy(пакет + 16, назначение, 4);
    записать_16(пакет + 20, порт_источника);
    записать_16(пакет + 22, порт_назначения);
    записать_32(пакет + 24, номер);
    пакет[32] = 0x50;
    пакет[33] = флаги;
    записать_16(пакет + 34, 4096);
    if (длина != 0) {
        memcpy(пакет + 40, данные, длина);
    }
    return всего;
}

static int обработать(d2k_session *сессия, const uint8_t *пакет, size_t длина,
                      uint64_t время, uint8_t *буфер, d2k_result *результат) {
    if (d2k_session_packet(сессия, пакет, длина, время, буфер, 2048, результат) != 0) {
        return 0;
    }
    return результат->verdict == D2K_VERDICT_ACCEPT;
}

int main(void) {
    const uint8_t клиент[4] = {192, 0, 2, 10};
    const uint8_t сервер[4] = {198, 51, 100, 20};
    uint8_t приветствие[128];
    size_t длина_приветствия = собрать_приветствие(приветствие);
    uint8_t пакет[128];
    uint8_t буфер[2048];
    d2k_result результат;
    d2k_session *сессия = d2k_session_new(64, 8);
    if (сессия == NULL) {
        fputs("не создана сессия C-эталона\n", stderr);
        return 2;
    }

    size_t длина = собрать_tcp(пакет, клиент, сервер, 41000, 443, 0x02, 64, 700,
                               NULL, 0);
    if (!обработать(сессия, пакет, длина, 1000, буфер, &результат)) {
        return 3;
    }
    длина = собрать_tcp(пакет, сервер, клиент, 443, 41000, 0x12, 124, 900,
                        NULL, 0);
    if (!обработать(сессия, пакет, длина, 2000, буфер, &результат)) {
        return 4;
    }
    длина = собрать_tcp(пакет, клиент, сервер, 41000, 443, 0x18, 64, 701,
                        приветствие, длина_приветствия);
    if (!обработать(сессия, пакет, длина, 3000, буфер, &результат)) {
        return 5;
    }
    длина = собрать_tcp(пакет, сервер, клиент, 443, 41000, 0x14, 127, 900,
                        NULL, 0);
    пакет[1] = 0x2e;
    записать_16(пакет + 4, 0x5a17);
    if (!обработать(сессия, пакет, длина, 4000, буфер, &результат)) {
        return 6;
    }

    const d2k_journal *журнал = d2k_session_journal(сессия);
    const d2k_jrn_entry *наблюдение = NULL;
    for (size_t индекс = 0; индекс < d2k_journal_count(журнал); индекс++) {
        const d2k_jrn_entry *запись = d2k_journal_at(журнал, индекс);
        if (запись != NULL && запись->kind == D2K_JRN_SUSPECT &&
            запись->code == D2K_SUSPECT_RST) {
            наблюдение = запись;
        }
    }
    if (наблюдение == NULL) {
        fputs("C-эталон не записал ранний RST\n", stderr);
        d2k_session_free(сессия);
        return 7;
    }

    printf("R2O_DIFF code=%u ttl=%u ref=%u tos=%u ipid=%u planned=%u shape=%u client_is_low=1\n",
           наблюдение->code, наблюдение->d_ttl, наблюдение->d_ref_ttl,
           наблюдение->d_tos, наблюдение->d_ipid, наблюдение->d_planned,
           наблюдение->d_client_shape);
    d2k_session_free(сессия);
    return 0;
}
